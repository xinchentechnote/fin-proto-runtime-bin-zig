//! Binary codec primitives shared by every fin-proto-*-zig generated message.
//!
//! The runtime mirrors `fin-proto-runtime-bin-rs` (crate `binary_codec`):
//! a growable encode buffer and a cursor over an immutable byte slice,
//! fixed/dynamic string helpers with padding semantics, length-prefixed
//! list helpers and endian-aware scalar access.
//!
//! Decoding never copies string payloads: fixed char arrays and dynamic
//! strings are returned as sub-slices of the caller's input buffer, so they
//! stay valid only as long as the input bytes do. `decode` allocates only
//! the outer slice of `repeat` fields; the matching `deinit` frees exactly
//! those allocations with the same allocator.

const std = @import("std");
const nativeEndian: std.builtin.Endian = @import("builtin").cpu.arch.endian();

/// Error set produced by every `decode` generated by fin-protoc.
pub const DecodeError = error{
    OutOfMemory,
    UnexpectedEof,
    InvalidUtf8,
    UnknownMessageType,
};

/// Growable byte buffer used as the encode side of the codec.
///
/// The buffer carries the configured byte order (`.big` by default, matching
/// the `LittleEndian = false` DSL option), so generated code never needs
/// `_le` call variants.
pub const Buffer = struct {
    allocator: std.mem.Allocator,
    data: []u8 = &.{},
    len: usize = 0,
    endian: std.builtin.Endian = .big,

    pub fn init(allocator: std.mem.Allocator, endian: std.builtin.Endian) Buffer {
        return .{ .allocator = allocator, .endian = endian };
    }

    pub fn deinit(self: *Buffer) void {
        if (self.data.len > 0) self.allocator.free(self.data);
        self.data = &.{};
        self.len = 0;
    }

    /// Reset the buffer for another encode round, keeping the allocated
    /// capacity (the streaming-write / benchmark idiom).
    pub fn reset(self: *Buffer) void {
        self.len = 0;
    }

    /// The bytes written so far.
    pub fn written(self: *const Buffer) []const u8 {
        return self.data[0..self.len];
    }

    fn reserve(self: *Buffer, additional: usize) error{OutOfMemory}!void {
        const needed = self.len + additional;
        if (needed <= self.data.len) return;
        var cap = self.data.len;
        while (cap < needed) cap = if (cap == 0) 64 else cap * 2;
        if (self.data.len == 0) {
            self.data = try self.allocator.alloc(u8, cap);
        } else {
            self.data = try self.allocator.realloc(self.data, cap);
        }
    }

    /// Append raw bytes.
    pub fn writeBytes(self: *Buffer, bytes: []const u8) error{OutOfMemory}!void {
        try self.reserve(bytes.len);
        @memcpy(self.data[self.len..][0..bytes.len], bytes);
        self.len += bytes.len;
    }

    /// Append one scalar (integer or float), honouring the buffer's endianness.
    pub fn put(self: *Buffer, comptime T: type, value: T) error{OutOfMemory}!void {
        const n = @sizeOf(T);
        try self.reserve(n);
        const dest: *[n]u8 = self.data[self.len..][0..n];
        writeScalar(T, dest, value, self.endian);
        self.len += n;
    }

    /// Overwrite a previously written scalar in place (used by `@lengthOf`
    /// fields to patch the real length after the target field is encoded).
    pub fn patch(self: *Buffer, comptime T: type, pos: usize, value: T) error{UnexpectedEof}!void {
        const n = @sizeOf(T);
        if (pos + n > self.len) return error.UnexpectedEof;
        const dest: *[n]u8 = self.data[pos..][0..n];
        writeScalar(T, dest, value, self.endian);
    }
};

fn writeScalar(comptime T: type, dest: *[@sizeOf(T)]u8, value: T, endian: std.builtin.Endian) void {
    var tmp: [@sizeOf(T)]u8 = std.mem.toBytes(value);
    if (nativeEndian != endian) std.mem.reverse(u8, &tmp);
    dest.* = tmp;
}

/// Read cursor over an immutable byte slice, the decode side of the codec.
pub const Reader = struct {
    data: []const u8,
    pos: usize = 0,
    endian: std.builtin.Endian = .big,

    pub fn init(data: []const u8, endian: std.builtin.Endian) Reader {
        return .{ .data = data, .endian = endian };
    }

    pub fn remaining(self: *const Reader) usize {
        return self.data.len - self.pos;
    }

    /// Consume and return the next `n` bytes (borrowed from the input).
    pub fn take(self: *Reader, n: usize) DecodeError![]const u8 {
        if (self.remaining() < n) return error.UnexpectedEof;
        const out = self.data[self.pos..][0..n];
        self.pos += n;
        return out;
    }

    /// Read one scalar (integer or float), honouring the reader's endianness.
    pub fn get(self: *Reader, comptime T: type) DecodeError!T {
        const n = @sizeOf(T);
        if (self.remaining() < n) return error.UnexpectedEof;
        const bytes: *const [n]u8 = self.data[self.pos..][0..n];
        self.pos += n;
        var tmp: [n]u8 = bytes.*;
        if (nativeEndian != self.endian) std.mem.reverse(u8, &tmp);
        return std.mem.bytesToValue(T, &tmp);
    }
};

fn writeLengthPrefix(comptime L: type, buf: *Buffer, n: usize) error{OutOfMemory}!void {
    try buf.put(L, @intCast(n));
}

fn readLengthPrefix(comptime L: type, r: *Reader) DecodeError!usize {
    return @intCast(try r.get(L));
}

fn trimRight(bytes: []const u8, pad_char: u8) []const u8 {
    var end = bytes.len;
    while (end > 0 and bytes[end - 1] == pad_char) end -= 1;
    return bytes[0..end];
}

fn trimLeft(bytes: []const u8, pad_char: u8) []const u8 {
    var start: usize = 0;
    while (start < bytes.len and bytes[start] == pad_char) start += 1;
    return bytes[start..];
}

// ---------------------------------------------------------------------------
// Fixed char arrays (DSL `char[N]` / `zchar[N]`)
// ---------------------------------------------------------------------------

/// Write a fixed-width char array, right-padded with spaces (default DSL
/// padding). Overlong input is truncated, mirroring `put_char_array`.
pub fn putCharArray(buf: *Buffer, s: []const u8, fixed_len: usize) error{OutOfMemory}!void {
    return putCharArrayWithPad(buf, s, fixed_len, ' ', false);
}

/// Write a fixed-width char array with an explicit pad character and side.
pub fn putCharArrayWithPad(buf: *Buffer, s: []const u8, fixed_len: usize, pad_char: u8, pad_left: bool) error{OutOfMemory}!void {
    const content = s[0..@min(s.len, fixed_len)];
    if (pad_left) {
        var written: usize = content.len;
        while (written < fixed_len) : (written += 1) try buf.put(u8, pad_char);
        try buf.writeBytes(content);
    } else {
        try buf.writeBytes(content);
        var written: usize = content.len;
        while (written < fixed_len) : (written += 1) try buf.put(u8, pad_char);
    }
}

/// Read a fixed-width char array and trim trailing spaces.
pub fn getCharArray(r: *Reader, fixed_len: usize) DecodeError![]const u8 {
    return trimRight(try r.take(fixed_len), ' ');
}

/// Read a fixed-width char array and trim the configured pad character.
pub fn getCharArrayTrimPad(r: *Reader, fixed_len: usize, pad_char: u8, pad_left: bool) DecodeError![]const u8 {
    const raw = try r.take(fixed_len);
    return if (pad_left) trimLeft(raw, pad_char) else trimRight(raw, pad_char);
}

// ---------------------------------------------------------------------------
// Dynamic strings (DSL `string` / `char[]`) with a length prefix of type L
// ---------------------------------------------------------------------------

pub fn putString(comptime L: type, buf: *Buffer, s: []const u8) error{OutOfMemory}!void {
    try writeLengthPrefix(L, buf, s.len);
    try buf.writeBytes(s);
}

pub fn getString(comptime L: type, r: *Reader) DecodeError![]const u8 {
    const bytes = try r.take(try readLengthPrefix(L, r));
    if (!std.unicode.utf8ValidateSlice(bytes)) return error.InvalidUtf8;
    return bytes;
}

// ---------------------------------------------------------------------------
// Length-prefixed lists (DSL `repeat ...`, prefix type from ArrayPrefixLenType)
// ---------------------------------------------------------------------------

/// List of basic scalar values.
pub fn putList(comptime T: type, comptime L: type, buf: *Buffer, items: []const T) error{OutOfMemory}!void {
    try writeLengthPrefix(L, buf, items.len);
    for (items) |item| try buf.put(T, item);
}

pub fn getList(comptime T: type, comptime L: type, allocator: std.mem.Allocator, r: *Reader) DecodeError![]const T {
    const items = try allocator.alloc(T, try readLengthPrefix(L, r));
    for (items) |*item| item.* = try r.get(T);
    return items;
}

/// List of nested messages; `T` must provide `encode`/`decode`.
pub fn putObjectList(comptime T: type, comptime L: type, buf: *Buffer, items: []const T) error{OutOfMemory}!void {
    try writeLengthPrefix(L, buf, items.len);
    for (items) |*item| try item.encode(buf);
}

pub fn getObjectList(comptime T: type, comptime L: type, allocator: std.mem.Allocator, r: *Reader) DecodeError![]const T {
    const items = try allocator.alloc(T, try readLengthPrefix(L, r));
    for (items) |*item| item.* = try T.decode(allocator, r);
    return items;
}

/// List of dynamic strings (outer count prefix L1, per-string prefix L2).
pub fn putStringList(comptime L1: type, comptime L2: type, buf: *Buffer, items: []const []const u8) error{OutOfMemory}!void {
    try writeLengthPrefix(L1, buf, items.len);
    for (items) |s| try putString(L2, buf, s);
}

pub fn getStringList(comptime L1: type, comptime L2: type, allocator: std.mem.Allocator, r: *Reader) DecodeError![]const []const u8 {
    const items = try allocator.alloc([]const u8, try readLengthPrefix(L1, r));
    for (items) |*s| s.* = try getString(L2, r);
    return items;
}

/// List of fixed-width char arrays, space padded (default DSL padding).
pub fn putFixedStringList(comptime L: type, buf: *Buffer, items: []const []const u8, fixed_len: usize) error{OutOfMemory}!void {
    return putFixedStringListWithPad(L, buf, items, fixed_len, ' ', false);
}

pub fn putFixedStringListWithPad(comptime L: type, buf: *Buffer, items: []const []const u8, fixed_len: usize, pad_char: u8, pad_left: bool) error{OutOfMemory}!void {
    try writeLengthPrefix(L, buf, items.len);
    for (items) |s| try putCharArrayWithPad(buf, s, fixed_len, pad_char, pad_left);
}

pub fn getFixedStringList(comptime L: type, allocator: std.mem.Allocator, r: *Reader, fixed_len: usize) DecodeError![]const []const u8 {
    return getFixedStringListTrimPad(L, allocator, r, fixed_len, ' ', false);
}

pub fn getFixedStringListTrimPad(comptime L: type, allocator: std.mem.Allocator, r: *Reader, fixed_len: usize, pad_char: u8, pad_left: bool) DecodeError![]const []const u8 {
    const items = try allocator.alloc([]const u8, try readLengthPrefix(L, r));
    for (items) |*s| s.* = try getCharArrayTrimPad(r, fixed_len, pad_char, pad_left);
    return items;
}

