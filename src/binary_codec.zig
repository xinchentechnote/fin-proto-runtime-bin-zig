const testing = std.testing;

const Point = struct {
    x: u16,
    y: i32,

    fn encode(self: Point, buf: *Buffer) error{OutOfMemory}!void {
        try buf.put(u16, self.x);
        try buf.put(i32, self.y);
    }

    fn decode(allocator: std.mem.Allocator, r: *Reader) DecodeError!Point {
        _ = allocator;
        return .{ .x = try r.get(u16), .y = try r.get(i32) };
    }
};

test "scalar put/get both endians" {
    inline for (.{ std.builtin.Endian.big, std.builtin.Endian.little }) |endian| {
        var buf = Buffer.init(testing.allocator, endian);
        defer buf.deinit();
        try buf.put(u8, 0xAB);
        try buf.put(i8, -42);
        try buf.put(u16, 0x1234);
        try buf.put(i16, -1234);
        try buf.put(u32, 0x12345678);
        try buf.put(i32, -123456);
        try buf.put(u64, 0x0123456789ABCDEF);
        try buf.put(i64, -123456789);
        try buf.put(f32, 1.5);
        try buf.put(f64, -2.25);

        var r = Reader.init(buf.written(), endian);
        try testing.expectEqual(@as(u8, 0xAB), try r.get(u8));
        try testing.expectEqual(@as(i8, -42), try r.get(i8));
        try testing.expectEqual(@as(u16, 0x1234), try r.get(u16));
        try testing.expectEqual(@as(i16, -1234), try r.get(i16));
        try testing.expectEqual(@as(u32, 0x12345678), try r.get(u32));
        try testing.expectEqual(@as(i32, -123456), try r.get(i32));
        try testing.expectEqual(@as(u64, 0x0123456789ABCDEF), try r.get(u64));
        try testing.expectEqual(@as(i64, -123456789), try r.get(i64));
        try testing.expectEqual(@as(f32, 1.5), try r.get(f32));
        try testing.expectEqual(@as(f64, -2.25), try r.get(f64));
        try testing.expectEqual(@as(usize, 0), r.remaining());
    }
}

test "scalar wire order is big endian by default" {
    var buf = Buffer.init(testing.allocator, .big);
    defer buf.deinit();
    try buf.put(u32, 0x01020304);
    try testing.expectEqualSlices(u8, &.{ 1, 2, 3, 4 }, buf.written());

    var buf_le = Buffer.init(testing.allocator, .little);
    defer buf_le.deinit();
    try buf_le.put(u32, 0x01020304);
    try testing.expectEqualSlices(u8, &.{ 4, 3, 2, 1 }, buf_le.written());
}

test "patch rewrites scalar in place" {
    var buf = Buffer.init(testing.allocator, .big);
    defer buf.deinit();
    try buf.put(u16, 0);
    try buf.put(u32, 99);
    try buf.patch(u16, 0, 7);
    try testing.expectEqualSlices(u8, &.{ 0, 7, 0, 0, 0, 99 }, buf.written());
    try testing.expectError(error.UnexpectedEof, buf.patch(u32, 3, 1));
}

test "reset keeps capacity and truncates" {
    var buf = Buffer.init(testing.allocator, .big);
    defer buf.deinit();
    try buf.writeBytes(&.{ 1, 2, 3, 4 });
    buf.reset();
    try testing.expectEqual(@as(usize, 0), buf.len);
    try buf.put(u32, 0x01020304);
    try testing.expectEqualSlices(u8, &.{ 1, 2, 3, 4 }, buf.written());
}

test "char array pad and trim" {
    var buf = Buffer.init(testing.allocator, .big);
    defer buf.deinit();
    try putCharArray(&buf, "abc", 6);
    try putCharArrayWithPad(&buf, "xy", 4, 0, false);
    try putCharArrayWithPad(&buf, "xy", 4, '0', true);
    try putCharArray(&buf, "toolongstring", 4); // truncated

    var r = Reader.init(buf.written(), .big);
    try testing.expectEqualStrings("abc", try getCharArray(&r, 6));
    try testing.expectEqualStrings("xy", try getCharArrayTrimPad(&r, 4, 0, false));
    try testing.expectEqualStrings("xy", try getCharArrayTrimPad(&r, 4, '0', true));
    try testing.expectEqualStrings("tool", try getCharArray(&r, 4));
    try testing.expectError(error.UnexpectedEof, getCharArray(&r, 4));
}

test "dynamic string roundtrip" {
    var buf = Buffer.init(testing.allocator, .big);
    defer buf.deinit();
    try putString(u16, &buf, "hello");
    var r = Reader.init(buf.written(), .big);
    try testing.expectEqualStrings("hello", try getString(u16, &r));

    var bad = Buffer.init(testing.allocator, .big);
    defer bad.deinit();
    try bad.put(u16, 1);
    try bad.put(u8, 0xFF);
    var bad_r = Reader.init(bad.written(), .big);
    try testing.expectError(error.InvalidUtf8, getString(u16, &bad_r));
}

test "list roundtrips" {
    var buf = Buffer.init(testing.allocator, .big);
    defer buf.deinit();
    try putList(u32, u16, &buf, &.{ 1, 2, 3 });
    try putStringList(u16, u16, &buf, &.{ "ab", "cde" });
    try putFixedStringList(u16, &buf, &.{ "aa", "b" }, 3);
    try putObjectList(Point, u16, &buf, &.{ .{ .x = 1, .y = -1 }, .{ .x = 2, .y = -2 } });

    var r = Reader.init(buf.written(), .big);
    const ints = try getList(u32, u16, testing.allocator, &r);
    defer testing.allocator.free(ints);
    try testing.expectEqualSlices(u32, &.{ 1, 2, 3 }, ints);

    const strings = try getStringList(u16, u16, testing.allocator, &r);
    defer testing.allocator.free(strings);
    try testing.expectEqualStrings("ab", strings[0]);
    try testing.expectEqualStrings("cde", strings[1]);

    const fixed = try getFixedStringList(u16, testing.allocator, &r, 3);
    defer testing.allocator.free(fixed);
    try testing.expectEqualStrings("aa", fixed[0]);
    try testing.expectEqualStrings("b", fixed[1]);

    const points = try getObjectList(Point, u16, testing.allocator, &r);
    defer testing.allocator.free(points);
    try testing.expectEqual(@as(u16, 1), points[0].x);
    try testing.expectEqual(@as(i32, -2), points[1].y);
}

test "reader rejects short input" {
    var r = Reader.init(&.{1, 2}, .big);
    try testing.expectError(error.UnexpectedEof, r.get(u32));
}
